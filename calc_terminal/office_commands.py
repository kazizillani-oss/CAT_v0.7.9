def cmd_pdf(arg: str) -> str:
    """PDF inspection, text extraction, and generation."""
    parts = arg.strip().split(None, 1)
    sub = parts[0].lower() if parts else "status"
    rest = parts[1].strip() if len(parts) > 1 else ""

    root = _get_workspace_root()

    if sub == "status":
        has_pypdf = False
        has_reportlab = False
        try:
            import pypdf
            has_pypdf = True
        except ImportError:
            pass
        try:
            import reportlab
            has_reportlab = True
        except ImportError:
            pass
        return (
            "📑 **PDF Processing Engine Status:**\n"
            f"- pypdf: {'✅ Installed' if has_pypdf else 'ℹ️ Not installed (`/pkg install pypdf`)'}\n"
            f"- reportlab: {'✅ Installed' if has_reportlab else 'ℹ️ Not installed (`/pkg install reportlab`)'}"
        )

    if sub == "info":
        if not rest:
            return "Usage: `/pdf info <filename.pdf>`"
        target = os.path.join(root, rest)
        if not os.path.exists(target):
            return f"❌ File not found: `{rest}`"
        size = os.path.getsize(target)
        return (
            f"📑 **PDF File Information:** `{rest}`\n"
            f"- File Size: {size / 1024:.1f} KB ({size} bytes)\n"
            f"- Path: `{target}`"
        )

    return "Usage: `/pdf <status|info <file>>`"


