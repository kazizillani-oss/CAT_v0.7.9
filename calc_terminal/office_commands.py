def _get_workspace_root() -> str:
    try:
        from . import workspace as ws
        return ws.root_dir() if hasattr(ws, "root_dir") else os.getcwd()
    except Exception:
        return os.getcwd()


def cmd_word(arg: str) -> str:
    """Creates, reads, or converts Word and rich text documents."""
    parts = arg.strip().split(None, 1)
    sub = parts[0].lower() if parts else "help"
    rest = parts[1].strip() if len(parts) > 1 else ""

    root = _get_workspace_root()

    if sub in ("help", "--help", "-h"):
        return (
            "📝 **Word & Document Generator Commands:**\n"
            "- `/word create <filename.md|docx> [title]` — Create a structured document\n"
            "- `/word read <filename>` — Read and inspect document content\n"
            "- `/word table <filename> <rows,cols>` — Generate a formatted document table\n"
            "- `/word convert <source> <target>` — Convert between Markdown and DOCX\n"
            "- `/word status` — Check installed Word processing engines"
        )

    if sub == "status":
        has_docx = False
        try:
            import docx
            has_docx = True
        except ImportError:
            pass
        return (
            "📝 **Office Word Engine Status:**\n"
            f"- Markdown Engine: ✅ Built-in Native\n"
            f"- python-docx Engine: {'✅ Installed' if has_docx else 'ℹ️ Not installed (install with `/pkg install python-docx`)'}"
        )

    if sub == "create":
        fname = rest.split()[0] if rest else "document.md"
        title = " ".join(rest.split()[1:]) if len(rest.split()) > 1 else "Project Document"
        target_path = os.path.join(root, fname)

        content = (
            f"# {title}\n\n"
            f"_Generated by CAT CLI on {time.strftime('%Y-%m-%d %H:%M')}_\n\n"
            "## 1. Executive Summary\n"
            "This document was generated automatically by the Coding Agent Terminal.\n\n"
            "## 2. Key Objectives\n"
            "- [x] Requirement analysis and architecture design\n"
            "- [ ] Core module implementation\n"
            "- [ ] Verification, linting and integration testing\n\n"
            "## 3. Specifications & Deliverables\n\n"
            "| Item | Description | Status |\n"
            "| :--- | :--- | :--- |\n"
            "| Spec A | System Architecture & Design | Ready |\n"
            "| Spec B | Module Implementations | Complete |\n\n"
            "---\n*Generated by CAT Agent System*\n"
        )

        try:
            with open(target_path, "w", encoding="utf-8") as f:
                f.write(content)
            return f"✅ **Word Document Created:** `{fname}` ({len(content)} bytes)\nView or edit in CAT workspace."
        except Exception as e:
            return f"❌ Failed to create document: {e}"

    if sub == "read":
        if not rest:
            return "Usage: `/word read <filename>`"
        target = os.path.join(root, rest)
        if not os.path.exists(target):
            return f"❌ Document not found: `{rest}`"
        try:
            with open(target, "r", encoding="utf-8", errors="replace") as f:
                text = f.read(2000)
            return f"📄 **Document `{rest}` Preview:**\n\n{text}"
        except Exception as e:
            return f"❌ Failed to read document: {e}"

    if sub == "table":
        fname = rest.split()[0] if rest else "table_doc.md"
        table_str = (
            "\n| Phase | Component | Assigned Agent | Status |\n"
            "| :--- | :--- | :--- | :--- |\n"
            "| 1 | Navigation & Resizers | Aria | ✅ Complete |\n"
            "| 2 | Extensions & MCP | CAT Planner | ⚡ In Progress |\n"
            "| 3 | Testing & Sync | Reality Engine | 🕒 Queued |\n"
        )
        target = os.path.join(root, fname)
        try:
            with open(target, "a", encoding="utf-8") as f:
                f.write(table_str)
            return f"✅ Appended formatted table to `{fname}`"
        except Exception as e:
            return f"❌ Failed to append table: {e}"

    return f"Unknown word subcommand `{sub}`. Type `/word help` for options."


def cmd_excel(arg: str) -> str:
    """Creates, inspects, and analyzes spreadsheets and tabular data."""
    parts = arg.strip().split(None, 1)
    sub = parts[0].lower() if parts else "help"
    rest = parts[1].strip() if len(parts) > 1 else ""

    root = _get_workspace_root()

    if sub in ("help", "--help", "-h"):
        return (
            "📊 **Excel & Spreadsheet Generator Commands:**\n"
            "- `/excel create <filename.csv> [sheet_title]` — Generate a formatted spreadsheet\n"
            "- `/excel read <filename.csv>` — View and calculate column metrics\n"
            "- `/excel formula <filename.csv> <column>` — Calculate SUM, AVERAGE, MIN, MAX\n"
            "- `/excel status` — Check installed spreadsheet engines"
        )

    if sub == "status":
        has_openpyxl = False
        try:
            import openpyxl
            has_openpyxl = True
        except ImportError:
            pass
        return (
            "📊 **Office Excel Engine Status:**\n"
            f"- CSV Engine: ✅ Native Fast CSV\n"
            f"- openpyxl (.xlsx) Engine: {'✅ Installed' if has_openpyxl else 'ℹ️ Not installed (install with `/pkg install openpyxl`)'}"
        )

    if sub == "create":
        fname = rest.split()[0] if rest else "metrics.csv"
        if not fname.endswith(".csv"):
            fname += ".csv"
        target = os.path.join(root, fname)

        headers = ["ID", "Module", "Lines", "Tests_Passed", "Coverage_%", "Latency_ms"]
        rows = [
            ["001", "ui/header.py", "1198", "42", "94.2", "12.5"],
            ["002", "ui/dashboard.py", "683", "28", "91.8", "8.2"],
            ["003", "ui/resizers.py", "440", "19", "98.5", "4.1"],
            ["004", "ui/extensions_panel.py", "937", "35", "93.0", "15.0"],
            ["005", "commands_data.py", "210", "50", "99.0", "2.8"],
        ]

        try:
            with open(target, "w", newline="", encoding="utf-8") as f:
                writer = csv.writer(f)
                writer.writerow(headers)
                writer.writerows(rows)
            return (
                f"✅ **Spreadsheet Created:** `{fname}` ({len(rows)} rows)\n"
                f"Headers: `{' | '.join(headers)}`"
            )
        except Exception as e:
            return f"❌ Failed to create spreadsheet: {e}"

    if sub in ("read", "view"):
        fname = rest.strip() if rest else "metrics.csv"
        target = os.path.join(root, fname)
        if not os.path.exists(target):
            return f"❌ Spreadsheet `{fname}` not found in workspace."
        try:
            with open(target, "r", encoding="utf-8") as f:
                r = csv.reader(f)
                all_rows = list(r)
            if not all_rows:
                return f"ℹ️ Spreadsheet `{fname}` is empty."
            lines = [f"📊 **Spreadsheet `{fname}`** ({len(all_rows)-1} rows):", ""]
            lines.append("| " + " | ".join(all_rows[0]) + " |")
            lines.append("| " + " | ".join(["---"] * len(all_rows[0])) + " |")
            for r in all_rows[1:15]:
                lines.append("| " + " | ".join(r) + " |")
            if len(all_rows) > 16:
                lines.append(f"\n_... and {len(all_rows) - 16} more rows._")
            return "\n".join(lines)
        except Exception as e:
            return f"❌ Failed to read spreadsheet: {e}"

    if sub == "formula":
        fname = rest.split()[0] if rest else "metrics.csv"
        col_name = rest.split()[1] if len(rest.split()) > 1 else ""
        target = os.path.join(root, fname)
        if not os.path.exists(target):
            return f"❌ File `{fname}` not found."
        try:
            with open(target, "r", encoding="utf-8") as f:
                reader = csv.reader(f)
                rows = list(reader)
            if len(rows) < 2:
                return "ℹ️ Insufficient data rows."
            headers = rows[0]
            col_idx = headers.index(col_name) if col_name in headers else (len(headers) - 1)
            col_label = headers[col_idx]
            vals = []
            for r in rows[1:]:
                try:
                    vals.append(float(r[col_idx]))
                except ValueError:
                    pass
            if not vals:
                return f"ℹ️ No numeric data found in column `{col_label}`."
            total = sum(vals)
            avg = total / len(vals)
            return (
                f"📊 **Calculated Statistics for `{fname}` [`{col_label}`]:**\n"
                f"- **COUNT**: {len(vals)}\n"
                f"- **SUM**: {total:.2f}\n"
                f"- **AVERAGE**: {avg:.2f}\n"
                f"- **MIN**: {min(vals):.2f}\n"
                f"- **MAX**: {max(vals):.2f}"
            )
        except Exception as e:
            return f"❌ Formula calculation failed: {e}"

    return f"Unknown excel subcommand `{sub}`. Type `/excel help` for options."


