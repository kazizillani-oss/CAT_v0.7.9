"""
CCT Project Workspace (spec section 16).

Before this module, generated content scattered across at least two
independently-hardcoded, inconsistently-named directories:
  - calc_terminal/scires.py wrote PNG snapshots to  ~/cct_exports
  - calc_terminal/report.py wrote notebook exports to ~/CCT_exports
(note the casing difference alone — these were never the same folder,
even by accident, on a case-sensitive filesystem).

This module gives every generated artifact ONE home:
  <config.workspace_directory>/<category>/<filename>
using the workspace_directory that's already been a real, working
config.py field since the last session (Settings item 8). Nothing
generated by AI/commands should "disappear into chat history" the way
the spec puts it — it should land in a place the person can browse.

Categories match the spec's list (section 16): simulations, images,
graphs, reports, scripts, research, calculations, projects. Not every
category has a producer wired up yet — see WIRED_INTO below for the
honest current state.
"""

import os
import sys
import time
from . import config as cctconfig

CATEGORIES = [
    "simulations", "images", "graphs", "reports",
    "scripts", "research", "calculations", "projects",
]

# Set by ui/app.py._open_folder()/_close_folder() whenever the user opens
# or closes a project via the Explorer sidebar's "Open Folder". When a
# project is open, it — not the fixed config.workspace_directory — is
# what root_dir()/resolve_writable_path() treat as "the workspace", so
# relative paths the AI creates ("demo.py", "src/main.py", ...) land
# inside the project the user actually has open in the File Explorer
# instead of a separate, always-there ~/cct_workspace folder the user
# never sees on screen. This was the literal bug in the review: AI
# writes always resolved to a hardcoded directory regardless of which
# folder was open. `None` (the default, and what a fresh session/the
# classic non-UI REPL always has) means "no project open" and root_dir()
# falls back to config.workspace_directory exactly as it always did —
# no behavior change for anyone who never opens a folder.
_active_project_root = None


def set_active_project(path):
    """Called by the UI the moment a folder is opened/closed via the
    Explorer sidebar. `path=None` clears it back to the configured
    workspace_directory fallback."""
    global _active_project_root
    if path is None:
        _active_project_root = None
        return
    _active_project_root = os.path.abspath(os.path.expanduser(str(path)))


def active_project():
    """The currently open IDE project folder, or None if none is open."""
    return _active_project_root

