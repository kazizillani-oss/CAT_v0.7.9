def app_directory():
    """The CCT application's own source directory (the folder that
    holds main.py + calc_terminal/). Used by detection to avoid
    declaring CCT itself to be the user's workspace."""
    try:
        base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        if os.path.exists(os.path.join(base, "main.py")):
            return os.path.abspath(base)
    except Exception:
        pass
    return os.path.abspath(os.getcwd())


def git_root(start=None):
    """The nearest enclosing git repository root for `start` (or the
    current working directory), via `git rev-parse --show-toplevel`.
    Returns None when git isn't installed or `start` isn't in a
    repository — never raises."""
    start = os.path.abspath(start or os.getcwd())
    import subprocess
    try:
        out = subprocess.run(
            ["git", "-C", start, "rev-parse", "--show-toplevel"],
            capture_output=True, text=True, timeout=15,
            encoding="utf-8", errors="replace")
        if out.returncode == 0:
            root = out.stdout.strip()
            return os.path.abspath(root) if root else None
    except Exception:
        pass
    return None


def git_branch(path):
    """Current branch of the repo containing `path`, or None."""
    import subprocess
    try:
        out = subprocess.run(
            ["git", "-C", path, "branch", "--show-current"],
            capture_output=True, text=True, timeout=15,
            encoding="utf-8", errors="replace")
        branch = out.stdout.strip()
        return branch or None
    except Exception:
        return None


def git_status_summary(path):
    """Short `git status --porcelain` summary: (changed, added,
    deleted) counts, or None when not a repo. Honest — counts real
    porcelain entries only."""
    import subprocess
    try:
        out = subprocess.run(
            ["git", "-C", path, "status", "--porcelain"],
            capture_output=True, text=True, timeout=20,
            encoding="utf-8", errors="replace")
        if out.returncode != 0:
            return None
        changed = added = deleted = 0
        for line in out.stdout.splitlines():
            code = line[:2].strip()
            if code.startswith("A") or code.startswith("??"):
                added += 1
            elif code.startswith("D"):
                deleted += 1
            elif code:
                changed += 1
        return {"changed": changed, "added": added, "deleted": deleted}
    except Exception:
        return None


def _vscode_workspace(cwd):
    """VS Code currently-open workspace (spec section 1, priority 2):
    a `*.code-workspace` file in the working directory (its "folders"
    paths are the real workspace folders), else a `.vscode/` marker
    folder meaning "this directory is the VS Code workspace". Returns
    the first valid folder path, or None."""
    try:
        for name in sorted(os.listdir(cwd)):
            if name.endswith(".code-workspace"):
                full = os.path.join(cwd, name)
                try:
                    with open(full, "r", encoding="utf-8") as f:
                        import json
                        data = json.load(f)
                    for folder in (data or {}).get("folders", []):
                        p = folder.get("path", "")
                        if not p:
                            continue
                        p = os.path.abspath(os.path.join(cwd, p))
                        if os.path.isdir(p):
                            return p
                except Exception:
                    continue
                return cwd
        if os.path.isdir(os.path.join(cwd, ".vscode")):
            return cwd
    except Exception:
        pass
    return None


def detect_workspace(cwd=None):
    """Automatic workspace detection (spec section 1) — returns the
    first valid workspace path in this priority order, or None:

      1. the current terminal working directory (when it isn't CCT's
         own app folder — a project-looking cwd is the workspace);
      2. the VS Code workspace (.code-workspace file / .vscode marker);
      3. the git repository root;
      4. the directory CCT was launched from;
      5. the last opened workspace (projects.last_opened()).

    Pure function: never mutates state, never writes files. Callers
    decide what to do with the result.

    v0.7.9.0 fix: candidates inside protected system roots
    (C:\\Windows, C:\\Program Files, ...) are skipped entirely —
    launching `cat` from PowerShell's default C:\\WINDOWS\\System32 used
    to adopt System32 as the workspace (and even record it into recent
    history), which then crashed generated-file creation with
    PermissionError."""
    cwd = os.path.abspath(cwd or os.getcwd())
    app_dir = app_directory()
    try:
        def _protected(path):
            norm = _norm_ci(path)
            for blocked in _BLOCKED_ROOTS:
                b = _norm_ci(blocked)
                if norm == b or norm.startswith(b + os.sep):
                    return True
            return False

        candidates = []
        # 1 — cwd itself, unless it IS the app or a protected system dir.
        if cwd != app_dir and not _protected(cwd):
            candidates.append(cwd)
        # 2 — VS Code workspace.
        vsc = _vscode_workspace(cwd)
        if vsc and vsc not in candidates:
            candidates.append(vsc)
        # 3 — git root.
        gr = git_root(cwd)
        if gr and gr not in candidates:
            candidates.append(gr)
        # 4 — launch directory (when it differs from cwd and isn't
        #    the app folder).
        try:
            launch = os.path.abspath(os.path.dirname(sys.argv[0]) or cwd)
            if launch != cwd and launch != app_dir and launch not in candidates:
                candidates.append(launch)
        except Exception:
            pass
        # 5 — last opened workspace.
        try:
            from . import projects
            last = projects.last_opened()
            if last and last not in candidates:
                candidates.append(last)
        except Exception:
            pass
        for path in candidates:
            if os.path.isdir(path) and not _protected(path):
                return os.path.abspath(path)
    except Exception:
        pass
    return None


def auto_load_workspace():
    """Run detection once at startup and, if a workspace was found,
    load it: record it in recent history and make it the active
    project root (the same state _open_folder would set). Returns the
    detected path, or None. Idempotent — safe to call from both UIs."""
    try:
        path = detect_workspace()
        if not path:
            return None
        from . import projects
        projects.record_opened(path)
        set_active_project(path)
        return path
    except Exception:
        return None
