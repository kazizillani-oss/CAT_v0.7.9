def root_dir(*, ensure=False):
    """The active workspace root: the currently open IDE project folder
    if one is open (see set_active_project()), otherwise the configured
    workspace_directory fallback.

    STRICT FIX v0.7.9.6: directory creation is now explicit-only. Callers
    that intend to WRITE must pass ensure=True; read-only callers
    (summary, list_category, path resolution for reads) must leave
    ensure=False (the default) so merely inspecting or opening an
    existing folder never creates files or subdirectories inside it.
    When ensure=False the directory is returned verbatim even if it does
    not yet exist — callers that need to list it handle the missing-dir
    case themselves (returning an empty listing).

    v0.7.9.0 fix preserved: creation is best-effort."""
    if _active_project_root is not None:
        d = _active_project_root
    else:
        cfg = cctconfig.get_config()
        d = os.path.expanduser(cfg.workspace_directory)
    if ensure:
        try:
            os.makedirs(d, exist_ok=True)
        except OSError:
            pass  # unwritable/protected root — callers fail honestly per-op
    return d


def category_dir(category, *, ensure=False):
    """Return the path for a workspace category.

    STRICT FIX v0.7.9.6: by default does NOT create the directory. Pass
    ensure=True only when the caller is about to write a file there
    (path_for, default_export_dir, scires._export_dir). Read paths
    (list_category, summary) use ensure=False so dashboards and
    inspections never scaffold the 8 default folders inside a user's
    existing project."""
    if category not in CATEGORIES:
        raise ValueError(f"Unknown workspace category: {category!r}. Valid: {CATEGORIES}")
    d = os.path.join(root_dir(ensure=ensure), category)
    if ensure:
        try:
            os.makedirs(d, exist_ok=True)
        except OSError:
            pass  # see root_dir(): creation is best-effort, never fatal
    return d


def ensure_category_dir(category):
    """Explicit creation helper — only call when the user explicitly
    requested a file in this category or the requested operation
    necessarily requires it. Returns the ensured directory."""
    return category_dir(category, ensure=True)


def path_for(category, filename):
    """Resolve (and ensure the directory exists for) a file that's
    about to be written into the workspace. Callers still do their own
    actual file writing — this just gives them the one correct path.

    This is an EXPLICIT creation path — the caller's intent is to write,
    so the category directory is ensured."""
    return os.path.join(category_dir(category, ensure=True), filename)


# Directories a write/delete/rename should never resolve into, even if
# the model asks nicely with a plausible-sounding reason — a narrow,
# named blocklist, not a claim of a full sandbox (spec section 20 asks
# for "prevent path traversal", not "prevent all filesystem access").
_BLOCKED_ROOTS = (
    "/etc", "/sys", "/proc", "/boot", "/dev", "/System", "/Library",
    "C:\\Windows", "C:\\Program Files", "C:\\Program Files (x86)",
)


def find_matching_workspace_path(query_path: str, base_dir: str = None) -> str:
    """Automate file path resolution: find real matching file in workspace.

    If query_path is 'index.html' or 'calculator/index.html', but the actual file
    is at '<base>/projects/calculator/index.html', finds and returns the real path.
    """
    if not query_path or not str(query_path).strip():
        return ""
    base = base_dir or root_dir()
    if not os.path.isdir(base):
        return ""

    raw_clean = str(query_path).strip().replace("\\", "/")
    # If starts with fake roots like /workspace/ or /project/, strip them
    for prefix in ("/workspace/", "workspace/", "/project/", "project/"):
        if raw_clean.lower().startswith(prefix):
            raw_clean = raw_clean[len(prefix):]
            break

    clean_query = os.path.normpath(raw_clean.lstrip("/\\"))
    # 1. Direct path check
    direct = os.path.normpath(os.path.join(base, clean_query))
    if os.path.exists(direct):
        return direct

    # 2. Search workspace
    target_name = os.path.basename(clean_query).lower()
    target_subpath = clean_query.replace("\\", "/").lower()

    exact_name_matches = []
    suffix_matches = []
    fuzzy_matches = []

    skip_dirs = {".git", "node_modules", "__pycache__", ".venv", "venv", ".pytest_cache", "dist", "build"}
    for root, dirs, files in os.walk(base):
        dirs[:] = [d for d in dirs if d not in skip_dirs and not d.startswith(".")]
        # Also check directories if query might be a folder
        for d in dirs:
            full_d = os.path.join(root, d)
            rel_d = os.path.relpath(full_d, base).replace("\\", "/").lower()
            if rel_d == target_subpath or rel_d.endswith("/" + target_subpath) or d.lower() == target_name:
                fuzzy_matches.append(full_d)

        for f in files:
            full_f = os.path.join(root, f)
            rel_f = os.path.relpath(full_f, base).replace("\\", "/").lower()
            if rel_f.endswith(target_subpath):
                suffix_matches.append(full_f)
            elif f.lower() == target_name:
                exact_name_matches.append(full_f)
            elif target_name in f.lower() or target_subpath in rel_f:
                fuzzy_matches.append(full_f)

    if suffix_matches:
        return suffix_matches[0]
    if exact_name_matches:
        return exact_name_matches[0]
    if fuzzy_matches:
        return fuzzy_matches[0]
    return ""


def resolve_writable_path(path):
    """Turn a model- or user-supplied path into a safe absolute path,
    for use by anything that creates/writes/deletes/renames a real
    file (calc_terminal/agent.py's write_file/delete_file/rename_file/
    create_folder tools).

    - A relative path resolves against the workspace root (root_dir()),
      not the process's current working directory, so "src/main.py"
      means the same real location regardless of how CCT was launched.
    - Automated path resolution: if the path is relative or points to
      a subfolder file like "index.html" or "calculator/index.html",
      it scans the active workspace to find the real matching path.
    - An absolute path is honored as given (normalized) — same as any
      other AI-IDE agent operating with the OS user's own permissions.
    - Raises ValueError (never silently substitutes a "safe" path) if
      the resolved path lands in a clearly-dangerous system root, or
      outside of both the workspace root and the user's home directory
      — the two places CCT has any real business writing.
    """
    if not path or not str(path).strip():
        raise ValueError("No path given.")
    expanded = os.path.expanduser(str(path).strip())
    base = root_dir()

    # If exact absolute path exists, use it
    if os.path.isabs(expanded) and os.path.exists(expanded):
        resolved = os.path.normpath(expanded)
    else:
        # Automated path resolution: match file in workspace
        auto_found = find_matching_workspace_path(expanded, base)
        if auto_found:
            resolved = auto_found
        elif os.path.isabs(expanded):
            resolved = os.path.normpath(expanded)
        else:
            resolved = os.path.normpath(os.path.join(base, expanded))

    for blocked in _BLOCKED_ROOTS:
        blocked_norm = _norm_ci(blocked)
        if resolved_ci := _norm_ci(resolved):
            if resolved_ci == blocked_norm or resolved_ci.startswith(blocked_norm + os.sep):
                raise ValueError(f"Refusing to touch a protected system path: {resolved}")

    home = os.path.expanduser("~")
    in_workspace = resolved == base or resolved.startswith(base + os.sep)
    in_home = resolved == home or resolved.startswith(home + os.sep)
    if not (in_workspace or in_home):
        raise ValueError(
            f"'{resolved}' is outside both the workspace ({base}) and your home "
            "directory — refusing to write there. Use a path under one of those."
        )
    return resolved


def _norm_ci(path):
    """Normalized + case-insensitive form of a path for protected-root
    comparison. Windows filesystems are case-insensitive ('C:/WINDOWS'
    and 'C:/Windows' are the same directory), so every blocklist
    comparison must go through this — a plain startswith() silently
    missed C:/WINDOWS/System32."""
    return os.path.normcase(os.path.normpath(os.path.abspath(
        os.path.expanduser(str(path)))))


def path_is_protected(path):
    """True when `path` sits inside (or equals) one of the protected
    system roots — used by projects.forget_protected() to purge bad
    recent-workspace entries and by detect_workspace() to refuse
    adopting e.g. C:\\WINDOWS\\System32 as a workspace. Never raises.
    Comparison is case-insensitive via _norm_ci()."""
    try:
        norm = _norm_ci(path)
    except Exception:
        return False
    for blocked in _BLOCKED_ROOTS:
        b = _norm_ci(blocked)
        if norm == b or norm.startswith(b + os.sep):
            return True
    return False


def resolve_readable_path(path):
    """Resolve a path for READ-ONLY tool access (read_file, archive_list,
    archive_validate, search). Read-only access is safe anywhere except
    the named protected system roots, so this accepts absolute paths
    anywhere on disk — an attached file on another drive can be listed
    without first being copied into the workspace. Raises ValueError for
    blocked roots and empty paths only."""
    if not path or not str(path).strip():
        raise ValueError("No path given.")
    expanded = os.path.expanduser(str(path).strip())
    base = root_dir()

    if os.path.isabs(expanded) and os.path.exists(expanded):
        resolved = os.path.normpath(expanded)
    else:
        auto_found = find_matching_workspace_path(expanded, base)
        if auto_found:
            resolved = auto_found
        elif os.path.isabs(expanded):
            resolved = os.path.normpath(expanded)
        else:
            resolved = os.path.normpath(os.path.join(base, expanded))

    for blocked in _BLOCKED_ROOTS:
        blocked_norm = _norm_ci(blocked)
        resolved_ci = _norm_ci(resolved)
        if resolved_ci == blocked_norm or resolved_ci.startswith(blocked_norm + os.sep):
            raise ValueError(f"Refusing to read a protected system path: {resolved}")
    return resolved


def resolve_tool_path(path, for_write=False):
    """Resolve a model-supplied path for a tool call: strict
    resolve_writable_path rules for mutations, relaxed read-only rules
    (any non-blocked location) for reads."""
    if for_write:
        return resolve_writable_path(path)
    try:
        return resolve_writable_path(path)
    except ValueError:
        return resolve_readable_path(path)


def list_category(category):
    d = category_dir(category)
    out = []
    try:
        names = sorted(os.listdir(d))
    except OSError:
        # Unreadable/uncreatable category dir (e.g. CAT launched from a
        # protected directory) — an empty listing, never a crash.
        return out
    for name in names:
        full = os.path.join(d, name)
        try:
            if os.path.isfile(full):
                st = os.stat(full)
                out.append({
                    "name": name,
                    "path": full,
                    "size": st.st_size,
                    "mtime": st.st_mtime,
                })
        except OSError:
            continue
    return out


def list_all():
    return {cat: list_category(cat) for cat in CATEGORIES}


def summary():
    """One line per non-empty category, newest file first-ish, for a
    quick /workspace overview without dumping every file.

    v0.7.9.0 fix: per-category failures (PermissionError et al.) are
    skipped, so the startup dashboard can always compose — launching
    `cat` from C:\\WINDOWS\\System32 used to crash the whole app here."""
    lines = []
    for cat in CATEGORIES:
        try:
            files = list_category(cat)
        except Exception:
            continue
        if not files:
            continue
        files.sort(key=lambda f: f["mtime"], reverse=True)
        newest = files[0]
        age = time.time() - newest["mtime"]
        when = "just now" if age < 60 else f"{int(age // 60)}m ago" if age < 3600 else f"{int(age // 3600)}h ago"
        lines.append((cat, len(files), newest["name"], when))
    return lines


